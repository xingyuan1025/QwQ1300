local function translateText(text)
    if not text or type(text) ~= "string" then return text end
    
    local lowerText = text:lower()
    for en, cn in pairs(Translations) do
        if lowerText == en:lower() then
            return cn
        end
    end
    
    local translated = text
    for en, cn in pairs(Translations) do
        local lowerEn = en:lower()
        local pattern = lowerEn:gsub("([%^%$%(%)%%%.%[%]%*%+%-%?])", "%%%1")
        translated = translated:gsub("(?i)" .. pattern, function(match)
 
            return cn
        end)
    end
    
    return translated
end

local translatedObjects = {}  

local function translateGuiElement(gui)
    if translatedObjects[gui] then return end
    pcall(function()
        local text = gui.Text
        if text and text ~= "" then
            local translatedText = translateText(text)
            if translatedText ~= text then
                gui.Text = translatedText
                translatedObjects[gui] = true
            end
        end
    end)
    
    if gui:IsA("TextLabel") or gui:IsA("TextButton") or gui:IsA("TextBox") then
        local connection = gui:GetPropertyChangedSignal("Text"):Connect(function()
            pcall(function()
                local newText = gui.Text
                if newText and newText ~= "" then
                    local translatedText = translateText(newText)
                    if translatedText ~= newText then
                        gui.Text = translatedText
                    end
                end
            end)
        end)
 
    end
end

local function scanAndTranslate(parent)
    for _, descendant in ipairs(parent:GetDescendants()) do
        if descendant:IsA("TextLabel") or descendant:IsA("TextButton") or descendant:IsA("TextBox") then
            translateGuiElement(descendant)
        end
    end
end

local function setupDescendantListener(parent)
    parent.DescendantAdded:Connect(function(descendant)
        task.wait(0.05)  
        if descendant:IsA("TextLabel") or descendant:IsA("TextButton") or descendant:IsA("TextBox") then
            translateGuiElement(descendant)
        else
            scanAndTranslate(descendant)
        end
    end)
    
    parent.AncestryChanged:Connect(function()
        task.wait(0.1)
        scanAndTranslate(parent)
    end)
end

local function setupTranslationEngine()
    local success, err = pcall(function()
        local mt = getrawmetatable(game)
        local oldIndex = mt.__newindex
        setreadonly(mt, false)
        
        mt.__newindex = newcclosure(function(t, k, v)
            if (t:IsA("TextLabel") or t:IsA("TextButton") or t:IsA("TextBox")) and k == "Text" then
                v = translateText(tostring(v))
            end
            return oldIndex(t, k, v)
        end)
        
        setreadonly(mt, true)
    end)
    
    if not success then
        warn("元表劫持失败:", err)
        
        local services = {
            game:GetService("CoreGui"),
            game:GetService("StarterGui"),
            game:GetService("GuiService"),
            game:GetService("Players").LocalPlayer:WaitForChild("PlayerGui", 10),
            game:GetService("Players").LocalPlayer:WaitForChild("PlayerScripts", 10)
        }
        
        for _, service in ipairs(services) do
            if service then
                setupDescendantListener(service)
                scanAndTranslate(service)
            end
        end
        
        local RunService = game:GetService("RunService")
        RunService.Heartbeat:Connect(function()
            for _, service in ipairs(services) do
                if service then
                    scanAndTranslate(service)
                end
            end
        end)
    else

        local services = {
            game:GetService("CoreGui"),
            game:GetService("Players").LocalPlayer:WaitForChild("PlayerGui", 10)
        }
        for _, service in ipairs(services) do
            if service then
                setupDescendantListener(service)
                scanAndTranslate(service)
            end
        end
    end
end

